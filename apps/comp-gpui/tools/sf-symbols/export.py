"""Exports the SF Symbols the app draws (the `sf` constants in
crates/app/src/icons.rs) from the bundled SF Pro cut as SVGs, plus the Rust
table of their metrics.

Each SVG's viewBox is the glyph's advance by the font's ascent + descent, the
box a CSS `.sf-symbol` span with `line-height: 1` centers, with the baseline at
y = ascent.

Usage: uv run tools/sf-symbols/export.py
"""

import re
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

APP = Path(__file__).resolve().parents[2] / "crates/app"
FONT = APP / "assets/fonts/SF-Pro-400.ttf"
ICONS_RS = APP / "src/icons.rs"
SVG_DIR = APP / "assets/sf"
TABLE_RS = APP / "src/icons/glyphs.rs"


def code_points():
    text = ICONS_RS.read_text()
    return sorted({int(h, 16) for h in re.findall(r"pub const \w+: u32 = 0x([0-9A-Fa-f]+);", text)})


def main():
    font = TTFont(FONT)
    upem = font["head"].unitsPerEm
    ascent = font["hhea"].ascent
    descent = -font["hhea"].descent
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]

    SVG_DIR.mkdir(parents=True, exist_ok=True)

    rows = []
    for code in code_points():
        name = cmap.get(code)
        if name is None:
            raise SystemExit(f"U+{code:X} is not in {FONT.name}")
        advance = hmtx[name][0]
        path = SVGPathPen(glyphs)
        glyphs[name].draw(TransformPen(path, (1, 0, 0, -1, 0, ascent)))
        bounds = BoundsPen(glyphs)
        glyphs[name].draw(bounds)
        x_min, y_min, x_max, y_max = (round(v) for v in bounds.bounds)
        (SVG_DIR / f"{code:X}.svg").write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" '
            f'viewBox="0 0 {advance} {ascent + descent}">'
            f'<path d="{path.getCommands()}"/></svg>\n'
        )
        rows.append(
            f"    Glyph {{\n"
            f"        code: 0x{code:X},\n"
            f"        advance: {advance}.0,\n"
            f"        ink: [{x_min}.0, {y_min}.0, {x_max}.0, {y_max}.0],\n"
            f'        svg: include_str!("../../assets/sf/{code:X}.svg"),\n'
            f"    }},\n"
        )

    space = hmtx[cmap[0x20]][0]
    TABLE_RS.parent.mkdir(parents=True, exist_ok=True)
    TABLE_RS.write_text(
        "// @generated by tools/sf-symbols/export.py from assets/fonts/SF-Pro-400.ttf.\n\n"
        "use super::Glyph;\n\n"
        f"pub const UNITS_PER_EM: f32 = {upem}.0;\n"
        f"pub const ASCENT: f32 = {ascent}.0;\n"
        f"pub const DESCENT: f32 = {descent}.0;\n"
        f"pub const SPACE_ADVANCE: f32 = {space}.0;\n\n"
        "pub const GLYPHS: &[Glyph] = &[\n" + "".join(rows) + "];\n"
    )
    print(f"{len(rows)} glyphs -> {SVG_DIR.relative_to(APP)}, {TABLE_RS.relative_to(APP)}")


if __name__ == "__main__":
    main()
